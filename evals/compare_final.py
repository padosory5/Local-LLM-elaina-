"""The final cleaned comparison: Phase 2, Phase 3 and the rerun after the fixes.

    .venv/Scripts/python.exe -m evals.compare_final
    .venv/Scripts/python.exe -m evals.compare_final --out docs/PHASE3_FINAL_RESULTS.md

Three runs of the same matrix on the same corpus, judge (rubric v3) and
Ollama version: Phase 2 (runtime/evals/p2), the Phase 3 rerun
(runtime/evals/p3) and the rerun after the four fixes that rerun exposed
(runtime/evals/p3f). Everything is scored the way evals/report.py scores
it; the router, the soft stages and speech are read from the turn records.

What it reports, as asked for the final decision: scenarios passing, scored
turns passing, correct values, p50/p95 turn latency, the router's first-call
latency and fallback rate, VRAM with the speech recogniser loaded, soft
stages on and off, and the communication properties that differ between the
models. ● marks a difference larger than both sides' run-to-run spread and
at least five points; single-run arms are never marked.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path
from statistics import mean

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from evals import compare, compare3, corpus, phase2, phase3  # noqa: E402
from evals.judge import DEFAULT_JUDGE  # noqa: E402

FINAL_ROOT = PROJECT_ROOT / "runtime" / "evals" / "p3f"
# The recogniser-loaded 27B arm, rerun at two context sizes to tell the
# context window's cost from the day's conditions.
VRAM_ROOT = PROJECT_ROOT / "runtime" / "evals" / "p3f-vram"
VRAM_CHECKS = (("final, context 6144 (rerun)", "ctx6144"),
               ("final, Ollama default context (rerun)", "ctxdefault"))
CALIBRATIONS = ("calibration-p2.json", "calibration-p3.json")

_cell, _clear, _seconds = compare._cell, compare._clear, compare._seconds


def _scen(runs):
    return [(r["measured"]["scenarios_passed"], r["measured"]["scenarios"]) for r in runs]


def _turns(runs):
    return [r["turn_passes"] for r in runs]


def _correct(runs):
    return [r["measured"]["correctness"] for r in runs]


def _lat(runs, key):
    return [r["latency"][key] for r in runs]


def _router(runs, key):
    return [r["router"][key] for r in runs]


def _fallback(runs):
    return [(r["router"]["fallback"], r["router"]["routed"]) for r in runs]


def _prop(runs, name):
    return [r["measured"]["properties"].get(name, (0, 0)) for r in runs]


def _vram(runs):
    values = [r["latency"]["vram_max"] for r in runs if r["latency"]["vram_max"]]
    return f"{max(values) / 1024:.1f} GB" if values else "-"


def _calibration_status() -> list[str]:
    import json

    lines = []
    for name in CALIBRATIONS:
        path = PROJECT_ROOT / "runtime" / "evals" / name
        if not path.exists():
            lines.append(f"- `{name}`: not found.")
            continue
        items = json.loads(path.read_text(encoding="utf-8")).get("items", [])
        wanted = sum(len(item.get("labels", {})) for item in items)
        given = sum(1 for item in items for value in item.get("labels", {}).values()
                    if str(value or "").strip())
        lines.append(f"- `{name}`: {given} of {wanted} labels given.")
    return lines


def write(p2: dict, p3: dict, final: dict, judge: str) -> str:
    lines: list[str] = []
    add = lines.append
    meta = next(iter(final.values()))[0]["meta"] if final else {}
    add("# Phase 3, final: the cleaned comparison")
    add("")
    add(f"*Generated by `evals/compare_final.py` on {datetime.now().strftime('%Y-%m-%d %H:%M')}. "
        f"Final runs from commit `{meta.get('commit', '?')}`"
        + (" with uncommitted changes" if meta.get("uncommitted_changes") else "")
        + (f", Ollama {meta['ollama']}" if meta.get("ollama") else "")
        + f". Rubric version {corpus.rubric_version()} (`{corpus.rubric_fingerprint()}`), "
        f"judge `{judge}`. Phase 2: runtime/evals/p2; Phase 3: runtime/evals/p3; "
        "final: runtime/evals/p3f.*")
    add("")
    add("● marks a difference larger than both sides' run-to-run spread and at "
        "least five points (▲ better, ▼ worse).")
    add("")

    # ------------------------------------------------------------ across phases
    add("## Across phases, model held fixed")
    add("")
    add("| arm | phase | scenarios passing | scored turns passing | correct values | p50 s | p95 s | router first call p50 s | router fallback |")
    add("|---|---|---|---|---|---|---|---|---|")
    for final_name in ("p3-8b-soft", "p3-8b-nosoft", "p3-27b-soft", "p3-27b-nosoft", "p3-8bq8-soft"):
        if final_name not in final:
            continue
        prior = phase3.BEFORE.get(final_name, "")
        rows = (("Phase 2", p2.get(prior, [])), ("Phase 3", p3.get(final_name, [])),
                ("final", final[final_name]))
        for phase, runs in rows:
            if not runs:
                continue
            mark = lambda new, old: _clear(new, old) if phase == "final" and old else ""  # noqa: E731
            base = p3.get(final_name, [])
            add(f"| `{final_name}` | {phase} | {_cell(_scen(runs))}{mark(_scen(runs), _scen(base))} "
                f"| {_cell(_turns(runs))}{mark(_turns(runs), _turns(base))} "
                f"| {_cell(_correct(runs))}{mark(_correct(runs), _correct(base))} "
                f"| {_seconds(_lat(runs, 'p50'))} | {_seconds(_lat(runs, 'p95'))} "
                f"| {_seconds(_router(runs, 'first_p50'))} | {_cell(_fallback(runs))} |")
    add("")
    add("● on a final row is against the Phase 3 row above it.")
    add("")

    # ------------------------------------------------------------- the models
    add("## The models, pipeline held fixed (final)")
    add("")
    add("| arm | scenarios passing | scored turns passing | correct values | p50 s | p95 s "
        "| router first call p50 / p95 s | router fallback (repair p50 s) | VRAM, recogniser off | VRAM, recogniser loaded |")
    add("|---|---|---|---|---|---|---|---|---|---|")
    voice = {"8b": final.get("v3-8b", []), "27b": final.get("v3-27b", [])}
    base = final.get("p3-8b-soft", [])
    for name in ("p3-8b-soft", "p3-27b-soft", "p3-8b-nosoft", "p3-27b-nosoft", "p3-8bq8-soft"):
        if name not in final:
            continue
        runs = final[name]
        model = "27b" if "27b" in name else ("8bq8" if "8bq8" in name else "8b")
        mark = lambda new, old: "" if name == "p3-8b-soft" else _clear(new, old)  # noqa: E731
        repair = [r["router"]["fallback_p50"] for r in runs if r["router"]["fallback"]]
        add(f"| `{name}` | {_cell(_scen(runs))}{mark(_scen(runs), _scen(base))} "
            f"| {_cell(_turns(runs))}{mark(_turns(runs), _turns(base))} "
            f"| {_cell(_correct(runs))} "
            f"| {_seconds(_lat(runs, 'p50'))} | {_seconds(_lat(runs, 'p95'))} "
            f"| {_seconds(_router(runs, 'first_p50'))} / {_seconds(_router(runs, 'first_p95'))} "
            f"| {_cell(_fallback(runs))}" + (f" ({mean(repair):.1f})" if repair else "")
            + f" | {_vram(runs)} | {_vram(voice.get(model, []))} |")
    add("")
    add("● here is against `p3-8b-soft`. VRAM is the most the card held at the "
        "end of any scenario, desktop included; the recogniser-loaded column "
        "is the `v3-*` arm for that model (six scenarios, speech recognition "
        "resident as in the app).")
    add("")

    # ------------------------------------------- with the recogniser loaded
    add("## With the speech recogniser loaded")
    add("")
    add("VRAM alone hides what matters here: a card that is full keeps working, "
        "because the Windows driver pages what does not fit into shared system "
        "memory, and generation slows several-fold without an error. So the "
        "`v3-*` arms are read by speed as well.")
    add("")
    add("| arm | phase | VRAM | turn p50 / p95 s | router first call p50 s | answer tok/s |")
    add("|---|---|---|---|---|---|")
    checks = [(label, compare3._load(VRAM_ROOT / folder, [a for a in phase3.ARMS if a.name == "v3-27b"], judge))
              for label, folder in VRAM_CHECKS]
    for name in ("v3-8b", "v3-27b"):
        rows = [("Phase 3", p3.get(name, [])), ("final", final.get(name, []))]
        if name == "v3-27b":
            rows += [(label, found.get(name, [])) for label, found in checks]
        for phase, runs in rows:
            if runs:
                add(f"| `{name}` | {phase} | {_vram(runs)} "
                    f"| {_seconds(_lat(runs, 'p50'))} / {_seconds(_lat(runs, 'p95'))} "
                    f"| {_seconds(_router(runs, 'first_p50'))} | {_seconds(_lat(runs, 'answer_tps'))} |")
    add("")
    add("The two context-size rows are the `v3-27b` arm run again back to back "
        "(runtime/evals/p3f-vram), the only difference being `ELAINA_NUM_CTX`.")
    add("")

    # -------------------------------------------------------- soft stages
    add("## Soft stages on and off (final)")
    add("")
    add("| model | soft on: scenarios / turns | soft off: scenarios / turns | `only_what_helps` on / off | `no_service_phrasing` on / off |")
    add("|---|---|---|---|---|")
    for model in ("8b", "27b"):
        on, off = final.get(f"p3-{model}-soft"), final.get(f"p3-{model}-nosoft")
        if on and off:
            add(f"| {model.upper()} | {_cell(_scen(on))} / {_cell(_turns(on))} "
                f"| {_cell(_scen(off))}{_clear(_scen(off), _scen(on))} / {_cell(_turns(off))}{_clear(_turns(off), _turns(on))} "
                f"| {_cell(_prop(on, 'only_what_helps'))} / {_cell(_prop(off, 'only_what_helps'))} "
                f"| {_cell(_prop(on, 'no_service_phrasing'))} / {_cell(_prop(off, 'no_service_phrasing'))} |")
    add("")

    # ----------------------------------------------- properties between models
    add("## Communication properties, 8B against 27B (final, soft stages on)")
    add("")
    eight, twenty7 = final.get("p3-8b-soft", []), final.get("p3-27b-soft", [])
    add("| property | 8B | 27B | difference |")
    add("|---|---|---|---|")
    for prop in corpus.rubric():
        a, b = _prop(eight, prop), _prop(twenty7, prop)
        if not any(t for _, t in a + b):
            continue
        rates_a = [p / t for p, t in a if t]
        rates_b = [p / t for p, t in b if t]
        gap = (mean(rates_b) - mean(rates_a)) if rates_a and rates_b else 0.0
        mark = _clear(b, a)
        add(f"| `{prop}` | {_cell(a)} | {_cell(b)} | {gap * 100:+.0f} pts{mark} |")
    add("")
    add("● means the 27B's rate differs from the 8B's by more than both runs' "
        "spread and at least five points. Rarely-yes properties (`concrete_first`, "
        "`says_what_it_solves`, `adapts_to_confusion`) are only established "
        "once the blind human labels below agree with the judge.")
    add("")

    # ------------------------------------------------------- the fixes, checked
    add("## The four fixes, checked")
    add("")
    add("| arm | Phase 3 router fallback | final router fallback | Phase 3 values deleted with evidence | final | turns given the explanation budget without asking | answers carrying an unasked example on a *state* question |")
    add("|---|---|---|---|---|---|---|")
    for name in ("p3-8b-soft", "p3-27b-soft", "p3-8b-nosoft", "p3-27b-nosoft"):
        before, after = p3.get(name, []), final.get(name, [])
        if not after:
            continue
        before_deleted = sum(r["integrity"]["values_deleted_with_evidence"] for r in before)
        after_deleted = sum(r["integrity"]["values_deleted_with_evidence"] for r in after)
        wrong_budget = sum(r.get("budget_checks", {}).get("explain_without_request", 0) for r in after)
        state_examples = sum(r.get("budget_checks", {}).get("state_with_example_goal", 0) for r in after)
        add(f"| `{name}` | {_cell(_fallback(before))} | {_cell(_fallback(after))} "
            f"| {before_deleted} | {after_deleted} | {wrong_budget} | {state_examples} |")
    add("")

    # -------------------------------------------------- integrity and speech
    add("## Pipeline integrity and speech (final)")
    add("")
    add("| arm | clock turns searched | values deleted with evidence | display changed by speech shaping | speech coverage | turns under 90% |")
    add("|---|---|---|---|---|---|")
    for name, runs in final.items():
        if name.startswith("d3-"):
            continue
        total = lambda key: sum(r["integrity"][key] for r in runs)  # noqa: E731
        add(f"| `{name}` | {total('clock_turns_searched')} of {total('clock_turns')} "
            f"| {total('values_deleted_with_evidence')} | {total('display_speech_shaped')} "
            f"| {mean(r['speech']['coverage_mean'] for r in runs):.2f} "
            f"| {sum(r['speech']['coverage_below_90'] for r in runs)} |")
    add("")

    # --------------------------------------------------------- follow-ups
    add("## Follow-ups (R9), reported apart")
    add("")
    add("| arm | phase | scored turns passing | answers rather than asks | stays on the subject | `adapts_to_confusion` |")
    add("|---|---|---|---|---|---|")
    for name in ("f3-8b", "f3-27b"):
        for phase, source in (("Phase 3", p3), ("final", final)):
            runs = source.get(name, [])
            if runs:
                add(f"| `{name}` | {phase} | {_cell(_turns(runs))} "
                    f"| {_cell([r['measured']['checks'].get('answers_not_asks', (0, 0)) for r in runs])} "
                    f"| {_cell([r['measured']['checks'].get('must_contain_any', (0, 0)) for r in runs])} "
                    f"| {_cell(_prop(runs, 'adapts_to_confusion'))} |")
    add("")

    # --------------------------------------------------------- drift
    add("## Drift check")
    add("")
    add("| arm | turns passing P2 / P3 / final | answer tok/s P2 / P3 / final |")
    add("|---|---|---|")
    for name in ("d3-8b", "d3-27b"):
        prior = phase3.BEFORE[name]
        rows = [p2.get(prior, []), p3.get(name, []), final.get(name, [])]
        add(f"| `{name}` | " + " / ".join(_cell(_turns(r)) for r in rows) + " | "
            + " / ".join(_seconds(_lat(r, "answer_tps")) for r in rows) + " |")
    add("")

    add("## Blind human labels")
    add("")
    add("The rarely-yes properties are established only when a person's blind "
        "labels agree with the judge (`evals/calibration.py score`).")
    add("")
    lines.extend(_calibration_status())
    add("")
    return "\n".join(lines) + "\n"


def _budget_checks(path: Path) -> dict:
    """Whether the corrected budget reached only the turns it should."""
    counts = {"explain_without_request": 0, "state_with_example_goal": 0}
    for record in compare3._records(path):
        context = record.get("context") or {}
        route = context.get("route") or {}
        limits = context.get("limits") or {}
        if not isinstance(route, dict) or not isinstance(limits, dict):
            continue
        from brain.response_budget import asks_for_information

        asked = asks_for_information(str(route.get("intent", "")),
                                     str(route.get("speech_act", "")),
                                     str(route.get("answer_shape", "")))
        if limits.get("budget") in ("explain", "elaborate") and not asked \
                and route.get("intent") != "clarification":
            counts["explain_without_request"] += 1
        if limits.get("shape") == "state" and str(route.get("answer_shape", "")) == "state":
            call = next((c for c in record.get("model_calls") or ()
                         if str(c.get("caller", "")).endswith(":collect_answer")), None)
            if call and "show one concrete case" in str(call.get("messages", "")):
                counts["state_with_example_goal"] += 1
    return counts


def load(root: Path, arms, judge: str) -> dict:
    found = compare3._load(root, arms, judge)
    for name, runs in found.items():
        for number, run in enumerate(runs, 1):
            run["budget_checks"] = _budget_checks(root / f"{name}-{number}")
    return found


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--judge", default=DEFAULT_JUDGE)
    parser.add_argument("--root", default=str(FINAL_ROOT))
    parser.add_argument("--out", default="")
    args = parser.parse_args()
    p2 = compare3._load(phase2.ROOT, phase2.ARMS, args.judge)
    p3 = compare3._load(phase3.ROOT, phase3.ARMS, args.judge)
    final = load(Path(args.root), phase3.ARMS, args.judge)
    if not final:
        print(f"No final runs under {args.root}.")
        return 1
    document = write(p2, p3, final, args.judge)
    if args.out:
        Path(args.out).write_text(document, encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        print(document)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
